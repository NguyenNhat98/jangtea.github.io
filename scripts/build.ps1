# Bundle the project's named ES modules into isolated module factories for file://.
# No package installation is needed. Rebuild after changing any file in js/.
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$factories = [Collections.Generic.List[string]]::new()
$utf8 = [Text.UTF8Encoding]::new($false)
$sources = Get-ChildItem -LiteralPath (Join-Path $projectRoot 'js') -Recurse -Filter '*.js' | Where-Object { $_.Name -ne 'bundle.js' -and $_.Name -notlike '*-standalone.js' }
foreach ($file in $sources) {
  $id = $file.FullName.Substring($projectRoot.Length + 1).Replace('\', '/')
  $source = [IO.File]::ReadAllText($file.FullName)
  $exports = [regex]::Matches($source, '(?m)^export\s+(?:async\s+)?(?:function|const|let|class)\s+(\w+)') | ForEach-Object { $_.Groups[1].Value }
  $getters = ($exports | ForEach-Object { "Object.defineProperty(exports, '$_', { enumerable: true, get: () => $_ });" }) -join "`n"
  $imports = [regex]::Matches($source, '(?m)^import\s+\{([^}]+)\}\s+from\s+[''"]([^''"]+)[''"];?')
  foreach ($match in $imports) {
    $dependencyPath = [IO.Path]::GetFullPath((Join-Path $file.DirectoryName $match.Groups[2].Value))
    if (!(Test-Path -LiteralPath $dependencyPath)) { throw "Missing dependency: $dependencyPath" }
    $dependencyId = $dependencyPath.Substring($projectRoot.Length + 1).Replace('\', '/')
    $bindings = $match.Groups[1].Value -replace '\s+as\s+', ': '
    $source = $source.Replace($match.Value, "const { $bindings } = require('$dependencyId');")
  }
  $source = [regex]::Replace($source, '(?m)^export\s+', '')
  if ($source -match '(?m)^import\s') { throw "Unsupported import syntax in $id" }
  $factories.Add("'$id': function(exports, require) {`n$getters`n$source`n}")
}
$header = @'
// Generated by scripts/build.ps1. Edit the ES modules, then rebuild.
(() => {
  'use strict';
  const factories = {
'@
$footer = @'
  };
  const cache = {};
  function require(id) {
    if (cache[id]) return cache[id];
    if (!factories[id]) throw new Error(`Unknown module: ${id}`);
    const exports = cache[id] = {};
    factories[id](exports, require);
    return exports;
  }
  require('js/main.js');
  if (require('js/config.js').DEBUG) window.__teaModules = require;
})();
'@
$output = $header + "`n" + ($factories -join ",`n") + "`n" + $footer
[IO.File]::WriteAllText((Join-Path $projectRoot 'js/bundle.js'), $output, $utf8)
Write-Output "Bundled $($sources.Count) modules into js/bundle.js"
